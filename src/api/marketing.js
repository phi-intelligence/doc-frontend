/**
 * Generate an AI image for marketing content.
 * @param {string} prompt - Image generation prompt
 * @param {object} options - Generation options
 * @param {string} options.content_id - Optional content ID to link to
 * @param {string} options.aspect_ratio - Aspect ratio: 1:1, 16:9, 4:5, 9:16, 2:1
 * @param {string} options.style - Style: professional, creative, minimalist, bold
 * @param {string} options.category - Category: social, blog, email, general
 * @returns {Promise<{success: boolean, id: string, file_url: string, ...}>}
 */
export async function generateMarketingImage(prompt, options = {}) {
  const response = await apiClient.post('/marketing/images/generate', {
    prompt,
    content_id: options.content_id,
    aspect_ratio: options.aspect_ratio || '1:1',
    style: options.style || 'professional',
    category: options.category || 'social'
  });
  return response.data;
}

