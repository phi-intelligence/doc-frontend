/**
 * Upload an image for marketing use.
 * @param {File} file - Image file to upload
 * @param {string} category - Image category
 * @param {string} contentId - Optional content ID to link to
 * @returns {Promise<{success: boolean, id: string, file_url: string, ...}>}
 */
export async function uploadMarketingImage(file, category = 'general', contentId = null) {
  const formData = new FormData();
  formData.append('file', file);
  
  const params = new URLSearchParams({ category });
  if (contentId) params.append('content_id', contentId);
  
  const response = await apiClient.post(`/marketing/images/upload?${params}`, formData, {
    headers: { 'Content-Type': 'multipart/form-data' }
  });
  return response.data;
}

